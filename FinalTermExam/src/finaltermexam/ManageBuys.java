    private void AddPurchaseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddPurchaseActionPerformed
        String clientName = ClientName.getText();
        String productName = ProductName.getText();
        int qty = Integer.parseInt(quantity.getText());
        int priceVal = Integer.parseInt(Price.getText());
        String dateVal = date.getText();

            try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/buyer_monitoring_system", "root", "")) {
            String sql = "INSERT INTO buys (clientName, productName, quantity, price, date) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement stmt = conn.prepareStatement(sql);
        
            stmt.setString(1, clientName);
            stmt.setString(2, productName);
            stmt.setInt(3, qty);
            stmt.setInt(4, priceVal);
            stmt.setString(5, dateVal);
            stmt.executeUpdate();
            JOptionPane.showMessageDialog(this, "Purchase added successfully!");
            cleardata();
            loadData();
            } 
            catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error adding purchase: " + e.getMessage());
         }       
    }//GEN-LAST:event_AddPurchaseActionPerformed

 

    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
        int row = purchaseTable.getSelectedRow();
            if (row < 0){
                JOptionPane.showMessageDialog(this, "Select a row to edit");
                return;
            }
        
        int buyID = Integer.parseInt(purchaseTable.getValueAt(row, 0).toString());
            try(Connection conn = connect()){
                String sql = "UPDATE buys SET quantity = ?, price = ?, date = ? WHERE buyID = ?";
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setInt(1, Integer.parseInt(quantity.getText()));
                stmt.setInt(2, Integer.parseInt(Price.getText()));
                stmt.setString(3, date.getText());
                stmt.setInt(4, buyID);
                
                int updatedRow = stmt.executeUpdate();
                    if(updatedRow > 0){
                    JOptionPane.showMessageDialog(this, "Record Successfully updated!");
                    loadData();
                }
                    stmt.close();
                    conn.close();  
                    cleardata();
            } 
            catch (Exception e){
                JOptionPane.showMessageDialog(this, "Error in updating records!" + e.getMessage());
        }                               
    }//GEN-LAST:event_UpdateActionPerformed

