    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        int selectedRow = purchaseTable.getSelectedRow();
    
             if (selectedRow < 0) {
                JOptionPane.showMessageDialog(this, "Please select a row to delete.");
                return;
            }
        int buyID = Integer.parseInt(purchaseTable.getValueAt(selectedRow, 0).toString());
        int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this record?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
    );
            if (confirm == JOptionPane.YES_OPTION) {
                try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/buyer_monitoring_system", "root", "")) {
                String sql = "DELETE FROM buys WHERE buyID = ?";
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setInt(1, buyID);
                    
                int rowsDeleted = stmt.executeUpdate();
                    if (rowsDeleted > 0) {
                        JOptionPane.showMessageDialog(this, "Record deleted successfully!");
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to delete the record.");
                    }
                    loadData();
                    stmt.close();
                } 
                catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, "Error deleting record: " + e.getMessage());
            }
        }      
    }//GEN-LAST:event_DeleteButtonActionPerformed

