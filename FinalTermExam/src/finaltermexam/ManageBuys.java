    private void getClientName(){
        String name = clientName.getText();
            if(name.isEmpty()){
                ClientName.setText("");
                return;
            }
        
        try (Connection conn = connect()) {
            String sql = "SELECT first_name, last_name FROM clients WHERE first_name = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, name);
            ResultSet rs = stmt.executeQuery();
            
            if (rs.next()) {
                ClientName.setText(rs.getString("first_name")+ " " + rs.getString("last_name"));
            } else {
                ClientName.setText("No Match Found!");
            }
            rs.close();
            stmt.close();
        } 
        catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading clients: " + e.getMessage());
        }
   }
    
    private void getProductName(){
        String name = productName.getText();
            if(name.isEmpty()){
                ProductName.setText("");
                return;
            }
        
        try(Connection conn = connect()){
           String sql = "SELECT name FROM products WHERE name = ?";
           PreparedStatement stmt = conn.prepareStatement(sql);
           stmt.setString(1, name);
           ResultSet rs = stmt.executeQuery();

        if (rs.next()) {
            ProductName.setText(rs.getString("name"));
        }else{
            ProductName.setText("No Match Found!");
        }
        rs.close();
        stmt.close();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error loading products: " + e.getMessage());
    }
}
    private void loadData(){
        DefaultTableModel model = (DefaultTableModel) purchaseTable.getModel();
        model.setRowCount(0);
        Connection conn = connect();
        
        try{
            String sql = "SELECT  * FROM buys";
            try(var stmt = conn.createStatement()){
            ResultSet rs = stmt.executeQuery(sql);
            while (rs.next()) {
                        Object[] row = {  
                            rs.getInt("buyID"),
                            rs.getString("clientName"),
                            rs.getString("productName"),
                            rs.getString("quantity"),
                            rs.getString("price"),
                            rs.getString("date")
                        };
                        model.addRow(row);
                    }
            rs.close();
            }
        }catch (Exception e){
         JOptionPane.showMessageDialog(this, "Load Error" + e.getMessage());
        }
    }
   
