    private void ExportTable(){
        try {
            FileWriter fw = new FileWriter("buys_export.csv");
                for (int j = 0; j < purchaseTable.getColumnCount(); j++) {
                    fw.write(purchaseTable.getColumnName(j) + ",");
                }
                    fw.write("\n");

        for (int i = 0; i < purchaseTable.getRowCount(); i++) {
            for (int j = 0; j < purchaseTable.getColumnCount(); j++) {
                Object cell = purchaseTable.getValueAt(i, j);
                fw.write("\"" + (cell != null ? cell.toString() : "") + "\",");
            }
            fw.write("\n");
        }
        fw.close();
            JOptionPane.showMessageDialog(this, "Exported to buys_export.csv!");
        } 
        catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_ReceiptActionPerformed

