    private Connection connect() {
        try {
            String url = "jdbc:mysql://localhost:3306/buyer_monitoring_system";
            String user = "root";
            String password = "";
            return DriverManager.getConnection(url, user, password);
        } 
        catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database connection failed: " + e.getMessage());
            return null;
        }
    }
    
    private void addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addActionPerformed
        String product = Product.getText();
        String code = Code.getText();
        String category = Category.getSelectedItem().toString();
        
            if (product.isEmpty()||code.isEmpty()||category.isEmpty()){
                JOptionPane.showMessageDialog(null, "Input Necessary Fields");
            }
            Connection conn = connect();
                if (conn != null) {
                    try {
                        Class.forName("com.mysql.cj.jdbc.Driver");
                        String sql = "INSERT INTO products (name, code, category) VALUES (?, ?, ?)";
                        PreparedStatement stmt = conn.prepareStatement(sql);
                        stmt.setString(1, product);
                        stmt.setString(2, code);
                        stmt.setString(3, category);
                        stmt.executeUpdate();
                        stmt.close();
                        conn.close();
                    JOptionPane.showMessageDialog(this, "Product added successfully!");
                    loadData();
                    
            Product.setText("");
            Code.setText("");
            Category.setSelectedIndex(0);
            Product.requestFocus();

            } 
            catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error saving to database: " + e.getMessage());
            } 
            catch (ClassNotFoundException ex) {
              Logger.getLogger(FinalTermExam.class.getName()).log(Level.SEVERE, null, ex);
          }
        }        
     
    }//GEN-LAST:event_addActionPerformed

