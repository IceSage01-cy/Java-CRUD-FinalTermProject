    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int selectedRow = ProductTable.getSelectedRow();
    
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a row to delete.");
            return;
        }
            int buyID = Integer.parseInt(ProductTable.getValueAt(selectedRow, 0).toString());
            int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this record?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
            );
            
            if (confirm == JOptionPane.YES_OPTION) {
                try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/buyer_monitoring_system", "root", "")) {
                String sql = "DELETE FROM products WHERE productID = ?";
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setInt(1, buyID);
                int rowsDeleted = stmt.executeUpdate();
                    if (rowsDeleted > 0) {
                        JOptionPane.showMessageDialog(this, "Record deleted successfully!");
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to delete the record.");
                    }
                        loadData();
                        stmt.close();
                } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error deleting record: " + e.getMessage());
            }
        }      
    }//GEN-LAST:event_jButton3ActionPerformed
    
    private void loadData() {
        DefaultTableModel model = (DefaultTableModel) ProductTable.getModel();
        model.setRowCount(0);
        Connection conn = connect();
        if (conn != null) {
            try {
                String sql = "SELECT * FROM products";
                try (Statement stmt = conn.createStatement()) {
                    ResultSet rs = stmt.executeQuery(sql);
                    while (rs.next()) {
                        Object[] row = {
                            rs.getInt("productID"),
                            rs.getString("name"),
                            rs.getString("code"),
                            rs.getString("category"),
                      };
                        model.addRow(row);
                    }
                    rs.close();
                }
                conn.close();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
            }
        }
    }

    
