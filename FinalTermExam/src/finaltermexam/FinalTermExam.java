    private void deleteFieldsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteFieldsActionPerformed
        int row = ClientTable.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a row to delete.");
        return;
    }
        
        int buyID = Integer.parseInt(ClientTable.getValueAt(row, 0).toString());
        int confirm = JOptionPane.showConfirmDialog(this,"Are you sure you want to delete this record?", "Confirm Delete",JOptionPane.YES_NO_OPTION);
           
        if (confirm == JOptionPane.YES_OPTION) {
            try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/buyer_monitoring_system", "root", "")) {
                String sql = "DELETE FROM clients WHERE clientID = ?";
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setInt(1, buyID);
            
            int rowsDeleted = stmt.executeUpdate();
                if (rowsDeleted > 0) {
                    JOptionPane.showMessageDialog(this, "Record deleted successfully!");
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to delete the record.");
                }
                loadData();
                stmt.close();
                cleardata();
                } 
            catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error deleting record: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_deleteFieldsActionPerformed

    private void updateFieldsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateFieldsActionPerformed
        int row = ClientTable.getSelectedRow();
        if (row < 0){
            JOptionPane.showMessageDialog(this, "Select a row to edit");
            return;
        }
        
        int clientID = Integer.parseInt(ClientTable.getValueAt(row, 0).toString());

            try(Connection conn = connect()){
                String sql = "UPDATE clients SET first_name = ?, middle_initial = ?, last_name = ?, address = ?, gender = ? WHERE clientID = ?";
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setString(1, fFirstName.getText());
                stmt.setString(2, fMiddleInitial.getText());
                stmt.setString(3, fLastName.getText());
                stmt.setString(4, fAddress.getText());
                stmt.setString(5, fGender.getText());
                stmt.setInt(6, clientID);
                
                int updatedRow = stmt.executeUpdate();
                    if(updatedRow > 0){
                        JOptionPane.showMessageDialog(this, "Record Successfully updated!");
                        loadData();
                    }
                stmt.close();
                conn.close(); 
                cleardata();
        } 
            catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error in updating records!");
        }      
    }//GEN-LAST:event_updateFieldsActionPerformed
