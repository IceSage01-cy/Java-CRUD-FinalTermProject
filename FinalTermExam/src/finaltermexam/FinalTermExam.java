    private void addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addActionPerformed
      String firstName = fFirstName.getText();
      String middleInitial = fMiddleInitial.getText();
      String lastName = fLastName.getText();
      String address = fAddress.getText();
      String gender = fGender.getText();

        if (firstName.isEmpty() || middleInitial.isEmpty() || lastName.isEmpty() || address.isEmpty() || gender.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields must be filled!");
            return;
        }

        Connection conn = connect();
        if (conn != null) {
            try {
                Class.forName("com.mysql.cj.jdbc.Driver");
                String sql = "INSERT INTO clients (first_name, middle_initial, last_name, address, gender) VALUES (?, ?, ?, ?, ?)";
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setString(1, firstName);
                stmt.setString(2, middleInitial);
                stmt.setString(3, lastName);
                stmt.setString(4, address);
                stmt.setString(5, gender);
                stmt.executeUpdate();
                stmt.close();
                conn.close();
                
            fFirstName.setText("");
            fMiddleInitial.setText("");
            fLastName.setText("");
            fAddress.setText("");
            fGender.setText("");
            fFirstName.requestFocus();
                
                JOptionPane.showMessageDialog(this, "Client added successfully!");
                loadData();

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error saving to database: " + e.getMessage());
            } catch (ClassNotFoundException ex) {
              Logger.getLogger(FinalTermExam.class.getName()).log(Level.SEVERE, null, ex);
          }
        }                                   
    }//GEN-LAST:event_addActionPerformed
